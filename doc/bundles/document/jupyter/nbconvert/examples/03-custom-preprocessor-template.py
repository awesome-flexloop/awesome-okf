# 自定义过滤器
# ============================================================
def add_border_filter(text):
    """给文本添加边框"""
    lines = text.splitlines()
    width = max(len(l) for l in lines) if lines else 40
    border = "+" + "-" * (width + 2) + "+"
    result = [border]
    for line in lines:
        result.append("| " + line.ljust(width) + " |")
    result.append(border)
    return "\n".join(result)


def first_line_filter(text):
    """只取第一行"""
    return str(text).splitlines()[0] if str(text).splitlines() else ""


