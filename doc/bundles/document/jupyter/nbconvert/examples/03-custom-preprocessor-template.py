import os
import nbformat
from traitlets import List, Unicode, Bool, Int, Dict


def create_demo_notebook(path="demo_custom.ipynb"):
    """创建一个用于演示定制的Notebook"""
    nb = nbformat.v4.new_notebook(metadata={
        "kernelspec": {"name": "python3"},
        "language_info": {"name": "python"}
    })
    
    nb.cells.append(nbformat.v4.new_markdown_cell("""# 自定义预处理器和模板演示

这个Notebook用于演示nbconvert的自定义扩展能力。

## 代码示例
"""))
    
    # 带标签的code cell（用于TagRemovePreprocessor）
    cell1 = nbformat.v4.new_code_cell("""# 这段代码会被正常导出
import this
print('Hello, nbconvert!')""")
    cell1.metadata["tags"] = []
    nb.cells.append(cell1)
    
    # 带有"solution"标签的cell
    cell2 = nbformat.v4.new_code_cell("""# @solution
# 这段代码带有solution标签，可以被预处理器移除
answer = 42
print(f"答案是: {answer}")""")
    cell2.metadata["tags"] = ["solution"]
    nb.cells.append(cell2)
    
    # 带有"hide_input"标签的cell
    cell3 = nbformat.v4.new_code_cell("""# 这段代码的输入会被隐藏，只显示输出
import datetime
print(f"生成时间: {datetime.datetime.now()}")""")
    cell3.metadata["tags"] = ["hide_input"]
    nb.cells.append(cell3)
    
    # Markdown带HTML注释
    nb.cells.append(nbformat.v4.new_markdown_cell("""## 数据表格

以下是一个简单的数据表格：

| 名称 | 值 |
|------|-----|
| A | 1 |
| B | 2 |
| C | 3 |

<!-- TODO: 添加更多内容 -->
"""))
    
    # Raw cell
    nb.cells.append(nbformat.v4.new_raw_cell("<!-- 这是raw cell，直接输出 -->\n<hr>"))
    
    with open(path, "w", encoding="utf-8") as f:
        nbformat.write(nb, f)
    return path


