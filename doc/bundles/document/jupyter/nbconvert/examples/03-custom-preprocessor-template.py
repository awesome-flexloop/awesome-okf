# 自定义预处理器1：基于标签移除cell
# ============================================================
from nbconvert.preprocessors import Preprocessor

class SolutionRemover(Preprocessor):
    """移除带有solution标签的cell（教师版→学生版）"""
    enabled = True
    
    def preprocess(self, nb, resources):
        new_cells = []
        for index, cell in enumerate(nb.cells):
            tags = cell.metadata.get("tags", [])
            if "solution" not in tags:
                cell, resources = self.preprocess_cell(cell, resources, index)
                new_cells.append(cell)
            else:
                print(f"  [SolutionRemover] 移除solution cell #{index}")
        nb.cells = new_cells
        return nb, resources
    
    def preprocess_cell(self, cell, resources, index):
        return cell, resources


class InputHider(Preprocessor):
    """隐藏带有hide_input标签的code cell的输入"""
    enabled = True
    
    def preprocess_cell(self, cell, resources, index):
        if cell.cell_type == "code":
            tags = cell.metadata.get("tags", [])
            if "hide_input" in tags:
                cell.metadata["transient"] = {"remove_source": True}
                print(f"  [InputHider] 隐藏cell #{index} 的输入")
        return cell, resources


class TOCGenerator(Preprocessor):
    """从Markdown标题生成目录"""
    enabled = True
    
    def preprocess(self, nb, resources):
        toc_items = []
        for index, cell in enumerate(nb.cells):
            if cell.cell_type == "markdown":
                for line in cell.source.splitlines():
                    if line.startswith("#"):
                        # 解析标题级别和文本
                        parts = line.split(" ", 1)
                        if len(parts) == 2:
                            level = len(parts[0])
                            title = parts[1].strip()
                            if level <= 3:  # 只收集1-3级标题
                                anchor = title.lower().replace(" ", "-")
                                toc_items.append({
                                    "level": level,
                                    "title": title,
                                    "anchor": anchor,
                                    "cell_index": index
                                })
        
        resources["toc"] = toc_items
        print(f"  [TOCGenerator] 提取了 {len(toc_items)} 个标题")
        
        for index, cell in enumerate(nb.cells):
            nb.cells[index], resources = self.preprocess_cell(cell, resources, index)
        return nb, resources
    
    def preprocess_cell(self, cell, resources, index):
        return cell, resources


class WatermarkAdder(Preprocessor):
    """添加水印/版权信息到resources"""
    enabled = True
    watermark_text = Unicode("Generated by nbconvert custom pipeline").tag(config=True)
    
    def preprocess(self, nb, resources):
        resources["watermark"] = self.watermark_text
        print(f"  [WatermarkAdder] 添加水印: {self.watermark_text}")
        for index, cell in enumerate(nb.cells):
            nb.cells[index], resources = self.preprocess_cell(cell, resources, index)
        return nb, resources
    
    def preprocess_cell(self, cell, resources, index):
        return cell, resources


